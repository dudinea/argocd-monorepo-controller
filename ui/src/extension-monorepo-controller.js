// Argo CD UI extension for the Monorepo Controller.
//
// Adds an item to the Application status panel showing the application's
// Change Revision: the commit that actually changed the manifests the
// application generates, as opposed to the latest commit in the repository.
// Multi source applications get one row per source.
//
// The values are read from the annotations the controller maintains, which the
// UI already has as part of the Application object, so this needs no backend.
//
// This is bundled by esbuild into a single self contained script,
// ui/dist/extension-monorepo-controller.js, which is what gets installed. Build it
// with "make build-ui-local"; the built file is committed.
//
// argocd-server serves it as part of /extensions.js: every file under
// /tmp/extensions whose name matches ^extension(.*)\.js$ is concatenated into that
// response, each one wrapped in its own try/catch block. Therefore:
//
//   * the bundle must be self contained, which is why it is a bundle,
//   * React is taken from the global scope, it must never be bundled,
//   * nothing may leak into the global scope,
//   * the output must stay ASCII, since the response has no charset,
//   * a failure here is only visible in the browser console as
//     "Extension extension-monorepo-controller.js failed to load: ...".
//
// ui/dev/render-test.js exercises the rendering against the built bundle, run it
// with "make test-ui-local".

import {repoUrl, revisionUrl} from './urls';

((window) => {
    const extensionsAPI = window.extensionsAPI;
    if (!extensionsAPI || !extensionsAPI.registerStatusPanelExtension) {
        console.error('argocd-monorepo-controller: extensionsAPI is not available, extension not registered');
        return;
    }

    const React = window.React;
    if (!React) {
        console.error('argocd-monorepo-controller: React is not available, extension not registered');
        return;
    }

    // Used to render tooltips into document.body, the way argo-ui does. Older Argo
    // CD versions may not expose it, in which case tooltips fall back to the
    // native title attribute.
    const ReactDOM = window.ReactDOM;
    const canRenderPopup = !!(
        ReactDOM && ReactDOM.createPortal && React.useState && React.useRef && window.document && window.document.body
    );

    const TITLE = 'Change Revision';
    const ID = 'monorepo_change_revision';

    const CHANGE_REVISION_ANN = 'mrp-controller.argoproj.io/change-revision';
    const CHANGE_REVISIONS_ANN = 'mrp-controller.argoproj.io/change-revisions';

    const UNKNOWN_REVISION = '\u2014';
    const UNKNOWN_REVISION_TITLE = 'No change revision has been calculated for this source yet';

    const HELP_TEXT =
        'The commit that actually changed the manifests generated by this application, ' +
        'as opposed to the most recent commit in the repository. Multi source applications ' +
        'show one revision per source, and Helm repository sources show a chart version. ' +
        'Maintained by the Argo CD Monorepo Controller.';

    // Argo CD styles the status panel item labels inline (see sectionLabel() in
    // application-status-panel.tsx), so there is no class to reuse for them.
    // #6d7f8b is argo-ui's ARGO_GRAY6_COLOR.
    const labelStyle = {
        display: 'flex',
        alignItems: 'flex-start',
        fontSize: '12px',
        fontWeight: 600,
        color: '#6d7f8b',
        minHeight: '18px'
    };

    const rowsStyle = {
        display: 'grid',
        gridTemplateColumns: 'auto 1fr',
        columnGap: '0.5em',
        alignItems: 'baseline'
    };

    // The status panel is narrow, so source names are truncated rather than
    // allowed to wrap. The full repository URL is available as a tooltip.
    const sourceNameStyle = {
        color: '#6d7f8b',
        maxWidth: '10em',
        overflow: 'hidden',
        textOverflow: 'ellipsis',
        whiteSpace: 'nowrap'
    };

    const revisionStyle = {fontFamily: 'monospace'};

    // Argo CD renders its tooltips with tippy.js 5 using its light theme, and both
    // stylesheets are part of the UI bundle, so they apply to any markup that uses
    // tippy's class names. Reproducing that markup therefore gives exactly the built
    // in font, background, colour and shadow - and keeps matching if Argo CD
    // restyles them - without being able to import tippy itself.
    const TOOLTIP_MAX_WIDTH = 350; // tippy's own default
    const TOOLTIP_GAP = 8; // leaves room for the arrow, which overhangs by 7px

    const tooltipPopup = (content, anchor) => {
        // tippy flips the tooltip below the target when it does not fit above
        const below = anchor.top < 80;
        const placement = below ? 'bottom' : 'top';
        return React.createElement(
            'div',
            {
                className: 'tippy-popper',
                'data-placement': placement,
                style: {
                    position: 'fixed',
                    left: Math.round(anchor.left + anchor.width / 2),
                    top: Math.round(below ? anchor.bottom + TOOLTIP_GAP : anchor.top - TOOLTIP_GAP),
                    transform: below ? 'translateX(-50%)' : 'translate(-50%, -100%)',
                    zIndex: 1000
                }
            },
            React.createElement(
                'div',
                {
                    className: 'tippy-tooltip light-theme',
                    'data-placement': placement,
                    'data-state': 'visible',
                    style: {maxWidth: TOOLTIP_MAX_WIDTH + 'px', textAlign: 'left'}
                },
                // the stylesheet only gives the arrow its shape and colour, tippy
                // places it with inline styles
                React.createElement('div', {className: 'tippy-arrow', style: {left: '50%', marginLeft: '-8px'}}),
                React.createElement('div', {className: 'tippy-content'}, content)
            )
        );
    };

    const PopupTooltip = (props) => {
        const [anchor, setAnchor] = React.useState(null);
        const trigger = React.useRef(null);

        const hide = () => setAnchor(null);
        const show = () => {
            const node = trigger.current;
            if (!node || !node.getBoundingClientRect) {
                return;
            }
            const rect = node.getBoundingClientRect();
            setAnchor({left: rect.left, top: rect.top, bottom: rect.bottom, width: rect.width});
        };

        // A fixed position popup would otherwise be left behind by a scroll
        React.useEffect(() => {
            if (!anchor) {
                return undefined;
            }
            window.addEventListener('scroll', hide, true);
            window.addEventListener('resize', hide);
            return () => {
                window.removeEventListener('scroll', hide, true);
                window.removeEventListener('resize', hide);
            };
        }, [anchor]);

        const target = React.cloneElement(props.children, {ref: trigger, onMouseEnter: show, onMouseLeave: hide});
        if (!anchor) {
            return target;
        }
        return React.createElement(
            React.Fragment,
            null,
            target,
            ReactDOM.createPortal(tooltipPopup(props.content, anchor), window.document.body)
        );
    };

    const TitleTooltip = (props) => React.cloneElement(props.children, {title: props.text});

    const Tooltip = canRenderPopup ? PopupTooltip : TitleTooltip;

    // Reproduces argo-ui's HelpIcon, which the built in panel items get through
    // sectionLabel(). The cursor signals that there is something to hover.
    const helpIcon = (text) =>
        React.createElement(
            Tooltip,
            {content: text, text: text},
            React.createElement(
                'span',
                {style: {marginLeft: '5px', cursor: 'help'}},
                React.createElement(
                    'span',
                    {style: {fontSize: 'smaller'}},
                    ' ',
                    React.createElement('i', {className: 'fa fa-question-circle help-tip'})
                )
            )
        );

    // The controller writes one entry per source, in spec.sources order, and
    // falls back to spec.source for single source applications. Note that an
    // application with a single entry under spec.sources is handled by the
    // controller's multi source code path, so the length of spec.sources is not
    // a reliable way to tell the two apart - only its presence is.
    const getSources = (application) => {
        const spec = (application && application.spec) || {};
        if (Array.isArray(spec.sources) && spec.sources.length > 0) {
            return spec.sources;
        }
        if (spec.source) {
            return [spec.source];
        }
        return [];
    };

    // Returns the change revisions as an array, or null when the application
    // carries no change revision annotation at all. Tolerant of hand edited
    // values: anything that is not a JSON array of strings falls back to the
    // singular annotation, and non string elements become empty.
    const getChangeRevisions = (application) => {
        const annotations = (application && application.metadata && application.metadata.annotations) || {};

        const revisions = annotations[CHANGE_REVISIONS_ANN];
        if (typeof revisions === 'string') {
            let parsed;
            try {
                parsed = JSON.parse(revisions);
            } catch (e) {
                parsed = null;
            }
            if (Array.isArray(parsed)) {
                return parsed.map((revision) => (typeof revision === 'string' ? revision : ''));
            }
        }

        const revision = annotations[CHANGE_REVISION_ANN];
        if (typeof revision === 'string') {
            return [revision];
        }

        return null;
    };

    // The annotation value is not always a commit SHA: it can be a branch name,
    // a tag, an unresolved short revision or, for Helm repository sources, a
    // chart version. Only abbreviate what is certainly a full SHA.
    const isFullSHA = (revision) => /^[0-9a-f]{40}$/.test(revision);

    // Helm repository sources hold a chart version instead of a commit, and
    // nothing in the value itself says so - only source.chart does. When the row
    // has no name column of its own the chart name is prefixed to the version to
    // give it context, otherwise the name column already carries it.
    const formatRevision = (revision, source, withChartName) => {
        if (!revision) {
            return UNKNOWN_REVISION;
        }
        if (source && source.chart) {
            return withChartName ? source.chart + ':' + revision : revision;
        }
        if (isFullSHA(revision)) {
            return revision.substring(0, 7);
        }
        return revision;
    };

    // A revision only has a commit URL when it really is a commit in a Git
    // repository on a host Argo CD knows how to build URLs for. A Helm chart
    // version is not a commit, so those are never linked even though the chart
    // repository host might parse.
    const commitURL = (revision, source) => {
        if (!revision || !source || !source.repoURL || source.chart) {
            return null;
        }
        return revisionUrl(source.repoURL, revision, false);
    };

    // Renders content as an external link when there is a URL for it, and as plain
    // content when there is not. Mirrors Argo CD's Revision component.
    const maybeLink = (url, content) => {
        if (!url) {
            return content;
        }
        return React.createElement(
            'a',
            {href: url, target: '_blank', rel: 'noopener noreferrer'},
            content,
            ' ',
            React.createElement('i', {className: 'fa fa-external-link-alt'})
        );
    };

    const sourceName = (source, index) => {
        if (source && source.name) {
            return source.name;
        }
        // For a chart source the chart name identifies it far better than the
        // Helm repository host does.
        if (source && source.chart) {
            return source.chart;
        }
        const repoURL = source && source.repoURL;
        if (repoURL) {
            const trimmed = repoURL.replace(/\/+$/, '').replace(/\.git$/, '');
            let name = trimmed.substring(trimmed.lastIndexOf('/') + 1);
            // scp style URLs such as git@host:repo.git have no slash to split on
            if (name.indexOf(':') >= 0) {
                name = name.substring(name.lastIndexOf(':') + 1);
            }
            if (name) {
                return name;
            }
        }
        return 'source ' + index;
    };

    // The displayed revision is abbreviated and is not a link, so the full value is
    // shown on hover, in the same tooltip style the built in panel items use.
    const revisionElement = (revision, source, withChartName, key) =>
        React.createElement(
            Tooltip,
            {
                key: key,
                content: revision
                    ? React.createElement('span', {style: revisionStyle}, revision)
                    : UNKNOWN_REVISION_TITLE,
                text: revision || UNKNOWN_REVISION_TITLE
            },
            React.createElement(
                'div',
                {style: revisionStyle},
                maybeLink(commitURL(revision, source), formatRevision(revision, source, withChartName))
            )
        );

    const sourceNameElement = (source, index) =>
        React.createElement(
            'div',
            {key: 'name-' + index, style: sourceNameStyle, title: (source && source.repoURL) || undefined},
            sourceName(source, index)
        );

    // Argo CD serves its API relative to the page's base href, so it can live under
    // a sub path. requests.ts does the same with toAbsURL('/api/v1'); hardcoding a
    // leading slash here would break those installations.
    const revisionMetadataURL = (application, revision, sourceIndex) => {
        const metadata = application.metadata || {};
        const url = new window.URL(
            'api/v1/applications/' +
                encodeURIComponent(metadata.name) +
                '/revisions/' +
                encodeURIComponent(revision) +
                '/metadata',
            window.document.baseURI
        );
        if (metadata.namespace) {
            url.searchParams.set('appNamespace', metadata.namespace);
        }
        if (application.spec && application.spec.project) {
            url.searchParams.set('project', application.spec.project);
        }
        // Zero based against the same source list the annotations are aligned with.
        // The wrong index silently returns a commit from another repository.
        url.searchParams.set('sourceIndex', String(sourceIndex));
        // versionId is deliberately omitted so the server uses the live spec
        return url.toString();
    };

    const errorText = (body, status) => {
        if (body && typeof body === 'object') {
            if (typeof body.error === 'string' && body.error) {
                return body.error;
            }
            if (typeof body.message === 'string' && body.message) {
                return body.message;
            }
        }
        return 'request failed with status ' + status;
    };

    const fetchRevisionMetadata = (application, revision, sourceIndex) =>
        window
            .fetch(revisionMetadataURL(application, revision, sourceIndex), {
                credentials: 'same-origin',
                headers: {Accept: 'application/json'}
            })
            .then((response) =>
                response
                    .json()
                    .catch(() => null)
                    .then((body) => {
                        if (!response.ok) {
                            throw new Error(errorText(body, response.status));
                        }
                        return body || {};
                    })
            );

    // Argo CD's own detail rows, used throughout its sliding panels
    const detailRow = (label, value, key, valueStyle) =>
        React.createElement(
            'div',
            {className: 'row white-box__details-row', key: key},
            React.createElement('div', {className: 'columns small-3'}, label),
            React.createElement('div', {className: 'columns small-9', style: valueStyle}, value)
        );

    const formatDate = (value) => {
        const date = new Date(value);
        return isNaN(date.getTime()) ? value : date.toLocaleString();
    };

    const metadataRows = (result) => {
        if (!result) {
            return [];
        }
        if (result.state === 'loading') {
            return [detailRow('Commit', 'Loading commit details...', 'loading')];
        }
        if (result.state === 'error') {
            return [detailRow('Commit', result.error, 'error', {color: '#e96d76'})];
        }

        const metadata = result.data || {};
        const rows = [];
        if (metadata.author) {
            const author = metadata.signatureInfo ? metadata.author + ' - ' + metadata.signatureInfo : metadata.author;
            rows.push(detailRow('Author', author, 'author'));
        }
        if (metadata.date) {
            rows.push(detailRow('Date', formatDate(metadata.date), 'date'));
        }
        if (metadata.tags && metadata.tags.length) {
            rows.push(detailRow('Tags', metadata.tags.join(', '), 'tags'));
        }
        if (metadata.message) {
            // there is room in the flyout, so the message is not truncated the way
            // the built in RevisionMetadataPanel truncates it to 64 characters
            rows.push(detailRow('Message', metadata.message, 'message', {whiteSpace: 'pre-wrap'}));
        }
        if (rows.length === 0) {
            rows.push(detailRow('Commit', 'No commit details available', 'empty'));
        }
        return rows;
    };

    const sourceBox = (source, revision, result, index) => {
        const rows = [];
        if (source && source.repoURL) {
            rows.push(detailRow('Repository', maybeLink(repoUrl(source.repoURL), source.repoURL), 'repo'));
        }
        if (source && source.chart) {
            rows.push(detailRow('Chart', source.chart, 'chart'));
        } else if (source && source.path) {
            rows.push(detailRow('Path', source.path, 'path'));
        }
        if (source && source.targetRevision) {
            rows.push(detailRow('Target revision', source.targetRevision, 'target'));
        }
        rows.push(
            detailRow(
                'Change revision',
                revision ? maybeLink(commitURL(revision, source), revision) : UNKNOWN_REVISION,
                'revision',
                revision ? revisionStyle : undefined
            )
        );
        metadataRows(result).forEach((row) => rows.push(row));

        return React.createElement(
            'div',
            {className: 'white-box', key: 'source-' + index, style: {marginBottom: '1em'}},
            React.createElement('p', null, sourceName(source, index)),
            React.createElement('div', {className: 'white-box__details'}, rows)
        );
    };

    // Argo CD renders status panel extension flyouts in a SlidingPanel without
    // isMiddle, so they get the default 90% width, while the built in panels - the
    // revision metadata one behind the SYNC STATUS ellipsis, for example - pass
    // isMiddle={true} and get 600px. registerStatusPanelExtension accepts no width
    // option, unlike registerTopBarActionMenuExt which has isMiddle, so the only way
    // to match the built in panels is to put the class on the panel ourselves.
    // Reusing argo-ui's own class instead of restating its width keeps us in step if
    // that width ever changes.
    const MIDDLE_CLASS = 'sliding-panel--is-middle';
    // the panel is still sliding out when our cleanup runs
    const CLOSE_ANIMATION_MS = 500;

    const useMiddlePanelWidth = (ref) => {
        React.useEffect(() => {
            const node = ref.current;
            const panel = node && node.closest && node.closest('.sliding-panel');
            // nothing to do if Argo CD has started setting it itself
            if (!panel || !panel.classList || panel.classList.contains(MIDDLE_CLASS)) {
                return undefined;
            }
            panel.classList.add(MIDDLE_CLASS);
            return () => {
                // removing it immediately would make the panel jump to full width
                // partway through the closing animation
                window.setTimeout(() => panel.classList.remove(MIDDLE_CLASS), CLOSE_ANIMATION_MS);
            };
        }, []);
    };

    // Opened from the panel item's ellipsis button. Argo CD renders it inside a
    // SlidingPanel and passes {application, tree}; tree is not needed here.
    const ChangeRevisionFlyout = (props) => {
        const application = props && props.application;
        const [results, setResults] = React.useState({});
        const rootRef = React.useRef(null);

        useMiddlePanelWidth(rootRef);

        const revisions = getChangeRevisions(application) || [];
        const sources = getSources(application);
        const rowCount = sources.length > 0 ? Math.min(revisions.length, sources.length) : revisions.length;

        React.useEffect(() => {
            let cancelled = false;
            const pending = {};
            for (let i = 0; i < rowCount; i++) {
                const source = sources[i];
                // chart sources carry a version, not a commit, and there is nothing
                // to look up for a revision that was never calculated
                if (!revisions[i] || (source && source.chart)) {
                    continue;
                }
                pending[i] = {state: 'loading'};
            }
            if (Object.keys(pending).length === 0) {
                return undefined;
            }
            setResults(pending);

            Object.keys(pending).forEach((key) => {
                const index = Number(key);
                fetchRevisionMetadata(application, revisions[index], index).then(
                    (data) => {
                        if (!cancelled) {
                            setResults((current) => Object.assign({}, current, {[index]: {state: 'ok', data: data}}));
                        }
                    },
                    (error) => {
                        if (!cancelled) {
                            setResults((current) =>
                                Object.assign({}, current, {[index]: {state: 'error', error: String(error.message || error)}})
                            );
                        }
                    }
                );
            });

            return () => {
                cancelled = true;
            };
        }, [application && application.metadata && application.metadata.name, revisions.join(',')]);

        if (rowCount === 0) {
            return React.createElement('div', {ref: rootRef}, React.createElement('h4', null, TITLE),
                React.createElement('p', null, 'This application has no change revision.'));
        }

        const boxes = [];
        for (let i = 0; i < rowCount; i++) {
            boxes.push(sourceBox(sources[i], revisions[i], results[i], i));
        }

        return React.createElement(
            'div',
            {ref: rootRef},
            React.createElement('h4', null, TITLE),
            React.createElement('p', null, 'The commit that last changed the manifests generated by this application.'),
            boxes
        );
    };

    // The status panel renders extensions without any wrapper markup, so the
    // component has to provide the application-status-panel__item block itself.
    const ChangeRevisionPanelItem = (props) => {
        const application = props && props.application;

        const revisions = getChangeRevisions(application);
        // Only applications the controller tracks carry the annotations. For
        // everything else the item is left out entirely rather than showing a
        // placeholder, so the panel stays clean in mixed installations.
        if (!revisions || revisions.length === 0) {
            return null;
        }

        const sources = getSources(application);
        // The two are index aligned. They can only disagree in length if the
        // annotation was edited by hand; render what both cover and ignore the
        // rest, throwing here would blank the whole status panel.
        const rowCount = sources.length > 0 ? Math.min(revisions.length, sources.length) : revisions.length;
        if (rowCount === 0) {
            return null;
        }

        let value;
        if (rowCount === 1) {
            value = revisionElement(revisions[0], sources[0], true);
        } else {
            const rows = [];
            for (let i = 0; i < rowCount; i++) {
                rows.push(sourceNameElement(sources[i], i));
                rows.push(revisionElement(revisions[i], sources[i], false, 'revision-' + i));
            }
            value = React.createElement('div', {style: rowsStyle}, rows);
        }

        return React.createElement(
            'div',
            {className: 'application-status-panel__item'},
            // sectionHeader() in application-status-panel.tsx lays the built in
            // items out this way: the label, then the button that opens the flyout
            React.createElement(
                'div',
                {style: {display: 'flex', alignItems: 'center'}},
                React.createElement(
                    'label',
                    {style: labelStyle},
                    rowCount > 1 ? 'CHANGE REVISIONS' : 'CHANGE REVISION',
                    helpIcon(HELP_TEXT)
                ),
                React.createElement(
                    'button',
                    {
                        className: 'argo-button application-status-panel__more-button',
                        onClick: () => props.openFlyout && props.openFlyout()
                    },
                    React.createElement('i', {className: 'fa fa-ellipsis-h'})
                )
            ),
            React.createElement('div', {className: 'application-status-panel__item-value'}, value)
        );
    };

    extensionsAPI.registerStatusPanelExtension(ChangeRevisionPanelItem, TITLE, ID, ChangeRevisionFlyout);
})(window);
